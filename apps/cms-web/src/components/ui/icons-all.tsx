/** One component for a name: what `Icon` renders for a name outside its core set. */
export function ICONS_BY_NAME({
  name,
  ...props
}: { name: IconName } & ComponentProps<PhosphorIcon>) {
  const Component = ICONS[name]
  return <Component {...props} />
}
