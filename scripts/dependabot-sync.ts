/**
 * `bun run dependabot:sync` writes `.github/dependabot.yml` (DOC-71 §11.5); `--check` fails when the file differs from
 * what it would write (stage `verify`). The `bun` entry ignores every module the Expo SDK bundles
 * (`expo/bundledNativeModules.json`, plus `expo` itself): those follow the SDK through `expo install --fix`, not npm
 * `latest` (DR-94). Run it again after an SDK upgrade. Every entry waits 7 days after a release
 * (`cooldown`, DR-242); security updates do not wait.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dir, '..')
const target = resolve(root, '.github/dependabot.yml')
const bundled = Object.keys(
  JSON.parse(readFileSync(resolve(root, 'node_modules/expo/bundledNativeModules.json'), 'utf8')),
)
const sdk = (
  JSON.parse(readFileSync(resolve(root, 'node_modules/expo/package.json'), 'utf8')) as {
    version: string
  }
).version
const ignored = ['expo', ...bundled].sort()
// NativeWind 4.2.7 (the Expo apps) throws "NativeWind only supports Tailwind CSS v3" on Tailwind 4, so a major of it waits
// for a NativeWind that supports v4 (a DR decides when). The ignore applies to every workspace on the root entry.
const majorIgnored = ['tailwindcss']

const text = `# Generated by \`bun run dependabot:sync\` from Expo ${sdk} (DOC-71 §11.5); do not edit by hand.
version: 2
updates:
  - package-ecosystem: bun
    directory: /
    schedule: { interval: weekly, day: monday, time: "02:00", timezone: Asia/Ho_Chi_Minh }
    cooldown: { default-days: 7 }
    open-pull-requests-limit: 10
    commit-message: { prefix: chore }
    groups:
      minor-and-patch:
        update-types: [minor, patch]
    # A major is its own pull request and needs a DR (DR-01, DR-82). The Expo-managed modules follow the SDK (DR-94).
    ignore:
${ignored.map((name) => `      - dependency-name: "${name}"`).join('\n')}
${majorIgnored.map((name) => `      - dependency-name: "${name}"\n        update-types: ["version-update:semver-major"]`).join('\n')}
  - package-ecosystem: github-actions
    directory: /
    schedule: { interval: weekly, day: monday, time: "02:00", timezone: Asia/Ho_Chi_Minh }
    cooldown: { default-days: 7 }
    commit-message: { prefix: ci }
    groups:
      actions:
        patterns: ["*"]
  - package-ecosystem: docker
    directory: /docker
    schedule: { interval: weekly, day: monday, time: "02:00", timezone: Asia/Ho_Chi_Minh }
    cooldown: { default-days: 7 }
    commit-message: { prefix: build, include: scope }
    groups:
      images:
        patterns: ["*"]
  - package-ecosystem: docker-compose
    directory: /docker
    schedule: { interval: weekly, day: monday, time: "02:00", timezone: Asia/Ho_Chi_Minh }
    cooldown: { default-days: 7 }
    commit-message: { prefix: build, include: scope }
    groups:
      images:
        patterns: ["*"]
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {}
  if (current !== text) {
    console.error('.github/dependabot.yml is out of date: run bun run dependabot:sync')
    process.exit(1)
  }
  console.log(`.github/dependabot.yml is current (${ignored.length} Expo-managed modules ignored)`)
} else {
  writeFileSync(target, text)
  console.log(`wrote .github/dependabot.yml (${ignored.length} Expo-managed modules ignored)`)
}
